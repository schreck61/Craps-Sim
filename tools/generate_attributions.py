"""Generate THIRD-PARTY-LICENSES.md for a release archive.

Runs `cargo bundle-licenses` (https://crates.io/crates/cargo-bundle-licenses)
to harvest the license of every crate compiled into the binary on this
platform, then renders a single readable attribution file:

  * an index of every crate with its version and license expression,
  * every distinct license text found in the crate packages, printed once
    and listing the crates it covers,
  * canonical license texts for crates that declare a license but do not
    package its text.

Crates that are multi-licensed with a copyleft *option* (e.g. "MIT OR
Apache-2.0 OR LGPL-2.1-or-later") are used under a permissive option, and
only that option's text is included.

Usage: python3 tools/generate_attributions.py [output-path]
"""

