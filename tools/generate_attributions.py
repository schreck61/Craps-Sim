CANONICAL_TEXTS = {
    "MIT": MIT_CANONICAL,
    "Zlib": ZLIB_CANONICAL,
    "BSL-1.0": BSL_CANONICAL,
}


def is_missing(text):
    return text in (None, "", "NOT FOUND")


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "THIRD-PARTY-LICENSES.md"
    # encoding is explicit: Windows would otherwise decode with the legacy
    # locale codepage, which cannot represent all bytes in license texts.
    raw = subprocess.run(
        ["cargo", "bundle-licenses", "--format", "json"],
        capture_output=True,
        encoding="utf-8",
        errors="replace",
        check=True,
    ).stdout
    libs = json.loads(raw)["third_party_libraries"]
    libs.sort(key=lambda l: (l["package_name"].lower(), l["package_version"]))

    # Distinct found texts, and missing texts grouped by license id.
    texts = {}  # sha1 -> {"text": str, "license": str, "crates": [str]}
    missing = defaultdict(list)  # license id -> [crate]
    elected_away = defaultdict(list)  # skipped copyleft option -> [crate]

    for lib in libs:
        crate = f'{lib["package_name"]} {lib["package_version"]}'
        expression = lib.get("license") or ""
        multi = " OR " in expression
        for lic in lib.get("licenses", []):
            lid = lic.get("license", "")
            if multi and lid.startswith(COPYLEFT_PREFIXES):
                elected_away[lid].append(crate)
                continue
            text = lic.get("text")
            if is_missing(text):
                missing[lid].append(crate)
            else:
                h = hashlib.sha1(text.encode()).hexdigest()
                entry = texts.setdefault(h, {"text": text, "license": lid, "crates": []})
                entry["crates"].append(crate)

    out = []
    out.append("# Third-Party Licenses\n")
    out.append(
        "This file lists every Rust crate compiled into this binary "
        "distribution of Craps-Sim, together with its license. It is "
        "generated per release platform by `tools/generate_attributions.py`. "
        "The embedded GUI fonts are attributed separately in "
        "THIRD-PARTY-NOTICES.md and the `licenses/` directory.\n"
    )
    if elected_away:
        opts = ", ".join(sorted(elected_away))
        out.append(
            f"Some crates are multi-licensed with a copyleft option ({opts}); "
            "this distribution uses those crates under their permissive "
            "option, whose text appears below.\n"
        )

    out.append("## Crate index\n")
    out.append("| Crate | Version | License |")
    out.append("| --- | --- | --- |")
    for lib in libs:
        out.append(
            f'| {lib["package_name"]} | {lib["package_version"]} | {lib.get("license") or "?"} |'
        )
    out.append("")

    out.append("## License texts\n")
    ordered = sorted(texts.values(), key=lambda e: (e["license"], e["crates"][0].lower()))
    for entry in ordered:
        crates = ", ".join(entry["crates"])
        out.append(f'### {entry["license"]} — {crates}\n')
        out.append("```text")
        out.append(entry["text"].rstrip("\n"))
        out.append("```\n")

    if missing:
        out.append("## Crates whose packages do not include a license text\n")
        out.append(
            "The following crates declare their license in metadata without "
            "packaging the text. The canonical text of each license follows; "
            "its copyright rests with the crate's authors.\n"
        )
        for lid in sorted(missing):
            crates = ", ".join(missing[lid])
            out.append(f"### {lid} — {crates}\n")
            if lid in FONT_LICENSE_FILES:
                out.append(
                    f"See `{FONT_LICENSE_FILES[lid]}` in this archive for the full text.\n"
                )
                continue
            canonical = CANONICAL_TEXTS.get(lid)
            if canonical is None and lid == "Apache-2.0":
                # Reuse the canonical Apache-2.0 text already harvested from
                # another crate (the license body is crate-independent).
                apache = [e for e in texts.values() if e["license"] == "Apache-2.0"]
                if apache:
                    canonical = max(apache, key=lambda e: len(e["crates"]))["text"]
            if canonical:
                out.append("```text")
                out.append(canonical.rstrip("\n"))
                out.append("```\n")
            else:
                out.append(
                    f"Full text: https://spdx.org/licenses/{lid}.html\n"
                )

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(
        f"wrote {out_path}: {len(libs)} crates, {len(texts)} distinct texts, "
        f"{sum(len(v) for v in missing.values())} canonical-text fallbacks"
    )


if __name__ == "__main__":
    main()
